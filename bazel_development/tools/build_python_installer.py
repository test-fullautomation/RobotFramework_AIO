def create_requirements_file(output_dir, source_requirements):
    """Copy requirements.txt to package."""
    if source_requirements and Path(source_requirements).exists():
        print(f"\n📋 Copying requirements.txt...")
        target = output_dir / "config" / "requirements.txt"
        shutil.copy2(source_requirements, target)
        print(f"  ✓ Copied: {target}")
        return target
    return None


def create_zip_package(output_dir, zip_name):
    """Create ZIP archive of the installation package."""
    print(f"\n📦 Creating ZIP package...")
    
    zip_path = output_dir.parent / f"{zip_name}.zip"
    
    with zipfile.ZipFile(zip_path, 'w', zipfile.ZIP_DEFLATED) as zipf:
        for root, dirs, files in os.walk(output_dir):
            for file in files:
                file_path = Path(root) / file
                arcname = file_path.relative_to(output_dir.parent)
                zipf.write(file_path, arcname)
                print(f"  ✓ Added: {arcname}")
    
    print(f"\n✅ ZIP package created: {zip_path}")
    print(f"   Size: {zip_path.stat().st_size / (1024*1024):.2f} MB")
    
    return zip_path


def main():
    parser = argparse.ArgumentParser(
        description='Build Python installation package with Bazel'
    )
    parser.add_argument(
        '-o', '--output',
        default='python_installer_output',
        help='Output directory name (default: python_installer_output)'
    )
    parser.add_argument(
        '-r', '--requirements',
        default='requirements.txt',
        help='Path to requirements.txt (default: requirements.txt)'
    )
    parser.add_argument(
        '--skip-build',
        action='store_true',
        help='Skip Bazel build step (use existing artifacts)'
    )
    parser.add_argument(
        '--no-zip',
        action='store_true',
        help='Do not create ZIP archive'
    )
    
    args = parser.parse_args()
    
    print("=" * 70)
    print("🚀 Python Installation Package Builder")
    print("=" * 70)
    
    # Step 1: Run Bazel build (unless skipped)
    if not args.skip_build:
        run_command(
            ['bazel', 'build', '//:python_with_deps'],
            "Building Python with dependencies"
        )
    else:
        print("\n⏭️  Skipping Bazel build (--skip-build)")
    
    # Step 2: Create output directory
    output_dir = Path.cwd() / args.output
    if output_dir.exists():
        print(f"\n🗑️  Removing existing output directory: {output_dir}")
        shutil.rmtree(output_dir)
    
    create_installer_structure(output_dir)
    
    # Step 3: Copy Python runtime
    copy_python_runtime(output_dir)
    
    # Step 4: Copy wheels
    copy_wheels(output_dir)
    
    # Step 5: Create installation scripts
    create_install_script_windows(output_dir, args.requirements)
    create_install_script_linux(output_dir, args.requirements)
    
    # Step 6: Create README
    create_readme(output_dir)
    
    # Step 7: Copy requirements.txt
    create_requirements_file(output_dir, args.requirements)
    
    # Step 8: Create ZIP package (optional)
    zip_path = None
    if not args.no_zip:
        zip_path = create_zip_package(output_dir, args.output)
    
    # Final summary
    print("\n" + "=" * 70)
    print("✅ Python Installation Package Build Complete!")
    print("=" * 70)
    print(f"\n📂 Output directory: {output_dir}")
    if zip_path:
        print(f"📦 ZIP package: {zip_path}")
    print("\n📋 Next steps:")
    print(f"   1. Distribute: {zip_path if zip_path else output_dir}")
    print(f"   2. Extract on target system")
    print(f"   3. Run installation script:")
    print(f"      - Windows: scripts\\install.bat")
    print(f"      - Linux:   bash scripts/install.sh")
    print()


if __name__ == '__main__':
    main()
